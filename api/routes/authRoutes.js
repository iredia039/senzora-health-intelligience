const express = require('express')
const routes = express.Router()
const { register, login, me, edit, requestPasswordChange, confirmPasswordChange, forgotPassword, resetPassword, verifyEmail, resendCode } = require('../controller/authController')
const facility = require('../controller/facilities')
const chatbot = require('../controller/chatbot')
const transcribe = require('../controller/transcribe')
const { listConversation, getConversation } = require('../controller/conversation')
const auth = require('../middleware/auth')

routes.post('/register', register)
routes.post('/verify-email', verifyEmail)
routes.post('/resend-code', resendCode)
routes.post('/login', login)
routes.post('/forgot-password', forgotPassword)
routes.post('/reset-password', resetPassword)
routes.get('/me', auth, me)
routes.patch('/me', auth, edit)
routes.post('/me/password/request', auth, requestPasswordChange)
routes.post('/me/password/confirm', auth, confirmPasswordChange)
routes.post('/chatbot', auth, chatbot)
routes.post('/transcribe', auth, express.raw({ type: 'audio/*', limit: '5mb' }), transcribe)
routes.get('/conversations', auth, listConversation)
routes.get('/conversations/:id', auth, getConversation)
routes.get('/facilities', facility)

module.exports = routes